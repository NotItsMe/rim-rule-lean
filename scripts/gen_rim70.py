"""Generate the Stage 8 Lean files from data/rim70.json.

Usage (from the project root):  python scripts/gen_rim70.py [--limit N]

Writes
  RimRule/Rim70/Data.lean       the 70 codes and their open/closed roles
  RimRule/Rim70/Basic.lean      the bundled hypotheses of Theorem 1(b)/(a)
  RimRule/Rim70/Convex{1,2}.lean  Theorem 1(b)/(a) hypotheses by `decide +kernel`,
                              "neither open- nor closed-convex", and `∅ ∈ C`, for each code
  RimRule/Rim70/Links{1,2}.lean   a collapse certificate per code (faces equal to their hull),
                              and `LocallyGoodC` via the cone lemma for the other faces
  RimRule/Rim70/Summary.lean    the list of all 70 codes, `all70_nodup` and `all70_spec`

The Lean kernel re-checks everything; this script only finds the certificates
(collapse sequences), by depth-first search with memoisation.
"""

import json
import sys
from itertools import combinations
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
N = 7  # neurons are Fin 7; paper labels 1..6, neuron 0 unused

HEADER = """-- This file is generated by scripts/gen_rim70.py from data/rim70.json. Do not edit by hand.

-- This project is not part of mathlib, so the mathlib copyright-header linter does not apply.
set_option linter.style.header false
"""


def fs(s):
    s = sorted(s)
    return "∅" if not s else "{" + ", ".join(map(str, s)) + "}"


def wrap(items, indent, width=100):
    """Join items with ", ", breaking lines so none exceeds `width`."""
    lines, cur = [], indent
    for k, it in enumerate(items):
        piece = it + ("," if k < len(items) - 1 else "")
        if cur.strip() and len(cur) + 1 + len(piece) > width:
            lines.append(cur.rstrip())
            cur = indent
        cur += ("" if not cur.strip() else " ") + piece
    lines.append(cur.rstrip())
    return "\n".join(lines)


def roles(r):
    return "⟨" + ", ".join(fs(x) for x in r) + "⟩"


# ---------------------------------------------------------------- hypotheses (pre-check)

def contains(c, *rs):
    u = set().union(*map(set, rs))
    return u <= c


def check_hyps(C, R, closed):
    i, j, k, l, m, p = map(set, R)
    ok = bool(i)
    ok &= all(contains(c, k) for c in C if contains(c, i, m) and not contains(c, j))  # H1m
    ok &= all(contains(c, l) for c in C if contains(c, j, m) and not contains(c, i))  # H2m
    ok &= any(contains(c, i, m, p) and not contains(c, j) for c in C)  # H5'
    ok &= any(contains(c, j, m, p) for c in C)  # H6
    ok &= any(contains(c, i, j, m) for c in C)  # H7
    ok &= not any(contains(c, i, j, k, m, p) for c in C)  # FA
    if closed:
        ok &= not any(contains(c, i, j, k, l, m) for c in C)  # FB
    else:
        ok &= any(contains(c, k, l) for c in C)  # H3
        ok &= not any(contains(c, k, l, m) for c in C)  # H4
    return ok


# ---------------------------------------------------------------- complexes and collapses

def maximal(C):
    return [c for c in C if not any(c < d for d in C)]


def link_delta(C, sigma):
    out = set()
    for r in range(N + 1):
        for t in combinations(range(N), r):
            t = frozenset(t)
            if not (t & sigma) and any((t | sigma) <= c for c in C):
                out.add(t)
    return frozenset(out)


def free_pairs(K):
    for s in K:
        if not s:
            continue
        sup = [t for t in K if s < t]
        if len(sup) == 1 and len(sup[0]) == len(s) + 1:
            yield s, sup[0]


def collapse_to_vertex(K):
    """Return (steps, v) collapsing K to {∅, {v}}, or None."""
    seen = set()

    def dfs(K):
        if len(K) == 2 and frozenset() in K:
            (v,) = [x for x in K if x]
            if len(v) == 1:
                return [], next(iter(v))
        if K in seen:
            return None
        seen.add(K)
        for s, t in sorted(free_pairs(K), key=lambda st: (-len(st[1]), sorted(st[1]), sorted(st[0]))):
            r = dfs(K - {s, t})
            if r is not None:
                return [(s, t)] + r[0], r[1]
        return None

    return dfs(K)


def missing_faces(C):
    Cset = set(C)
    M = maximal(C)
    faces = set()
    for r in range(1, len(M) + 1):
        for F in combinations(M, r):
            s = frozenset.intersection(*F)
            if s and s not in Cset:
                faces.add(s)
    return sorted(faces, key=lambda s: (len(s), sorted(s)))


# ---------------------------------------------------------------- output

CHUNKS = 2  # proof files per half, so `lake build` can check them in parallel

DATA_DOC = """/-!
# Stage 8 data: 70 codes that Theorem 1 rules out

Generated from `data/rim70.json`. Source: WheelsCode, github.com/aruysdeperez/WheelsCode,
`{Five,Six,Seven}Fac_WIRE_WHEEL_6.sage`. The filter solved = 0, wheel = 0, reduced = 1,
indecomposable = 1 gives 1,800 codes (96 + 535 + 1,169). These 70 are the ones among them
for which role assignments satisfying the hypotheses of both Theorem 1(b) and Theorem 1(a)
were found. Each code uses the neurons 1..6; as in `Census.lean` we use `Fin 7` and leave
neuron 0 unused. Each code comes with roles `(i,j,k,l,m,p)` for Theorem 1(b) (`openRoles`)
and for Theorem 1(a) (`closedRoles`), copied from the JSON.
-/
"""

BASIC = """/-!
# Stage 8: bundled hypotheses of Theorem 1

`Hyps1b C R` and `Hyps1a C R` are the hypotheses of `Theorem1b` and `Theorem1a`
(`RimRule/Defs.lean`), bundled so one `decide +kernel` checks them all.
`not_convex_of_hyps` applies `theorem1b` and `theorem1a`.
-/

namespace RimRule.Rim70

/-- `Core` is decidable, field by field. -/
instance {n : ℕ} (C : Finset (Finset (Fin n))) (R : Roles n) : Decidable (Core C R) :=
  decidable_of_iff (H1m C R ∧ H2m C R ∧ H5' C R ∧ H6 C R ∧ H7 C R ∧ FA C R)
    ⟨fun ⟨a, b, c, d, e, f⟩ => ⟨a, b, c, d, e, f⟩, fun ⟨a, b, c, d, e, f⟩ => ⟨a, b, c, d, e, f⟩⟩

/-- The hypotheses of `Theorem1b` (Defs.lean), bundled. -/
def Hyps1b {n : ℕ} (C : Finset (Finset (Fin n))) (R : Roles n) : Prop :=
  R.i.Nonempty ∧ Core C R ∧ H3 C R ∧ H4 C R

/-- The hypotheses of `Theorem1a` (Defs.lean), bundled. -/
def Hyps1a {n : ℕ} (C : Finset (Finset (Fin n))) (R : Roles n) : Prop :=
  R.i.Nonempty ∧ Core C R ∧ FB C R

instance {n : ℕ} (C : Finset (Finset (Fin n))) (R : Roles n) : Decidable (Hyps1b C R) := by
  unfold Hyps1b; infer_instance

instance {n : ℕ} (C : Finset (Finset (Fin n))) (R : Roles n) : Decidable (Hyps1a C R) := by
  unfold Hyps1a; infer_instance

/-- Theorem 1(b) and Theorem 1(a) together. -/
theorem not_convex_of_hyps {n : ℕ} {C : Finset (Finset (Fin n))} {Ro Rc : Roles n}
    (h : Hyps1b C Ro ∧ Hyps1a C Rc) : ¬ IsOpenConvex C ∧ ¬ IsClosedConvex C :=
  ⟨(theorem1b n C Ro h.1.1 h.1.2.1 h.1.2.2.1 h.1.2.2.2).1,
    theorem1a n C Rc h.2.1 h.2.2.1 h.2.2.2⟩

end RimRule.Rim70
"""

CONVEX_DOC = """/-!
# Stage 8: the codes are neither open-convex nor closed-convex (part {part} of {total})

For each code, `decide +kernel` checks every hypothesis of Theorem 1(b) with its open roles and
every hypothesis of Theorem 1(a) with its closed roles (`hyps`). Then `theorem1b` and `theorem1a`
give `not_convex`: the code is neither open-convex nor closed-convex. `isNeuralCode` checks
`∅ ∈ C`.
-/
"""

LINKS_DOC = """/-!
# Stage 8: the codes are locally good, up to one cited fact (part {part} of {total})

For each code, `cert` lists every nonempty face of `Δ(C)` that is not a codeword and equals its
hull (these include all intersections of maximal codewords), with a sequence of elementary
collapses that takes its link to a single vertex. `decide +kernel` checks the certificate
(`certOK`). `locallyGoodC_of_certOK` (`RimRule/LocallyGood.lean`) then gives `LocallyGoodC C`:
every other nonempty non-codeword face has a cone link, which collapses by the general lemma
`collapsible_of_cone`, so no face is skipped.

Collapsible ⇒ contractible is the one cited textbook fact, not proved here (see the module
doc of `RimRule/LocallyGood.lean`).
-/
"""


def write(path, imports, doc, body, namespace=True):
    parts = [imports, "\n", HEADER, "\n", doc]
    if namespace:
        parts += ["\nnamespace RimRule.Rim70\n", body, "\nend RimRule.Rim70\n"]
    else:
        parts.append(body)
    path.write_text("".join(parts), encoding="utf-8", newline="\n")


def main():
    limit = None
    if "--limit" in sys.argv:
        limit = int(sys.argv[sys.argv.index("--limit") + 1])
    data = json.loads((ROOT / "data" / "rim70.json").read_text(encoding="utf-8"))
    codes = data["codes"][:limit] if limit else data["codes"]
    out = ROOT / "RimRule" / "Rim70"
    out.mkdir(exist_ok=True)
    for old in out.glob("*.lean"):
        old.unlink()

    data_b, conv_b, links_b = [], [], []
    total_faces = 0
    for c in codes:
        name = c["id"]
        C = [frozenset(w) for w in c["codewords"]]
        assert len(set(C)) == len(C)
        assert check_hyps(C, c["open_roles_ijklmp"], closed=False), name
        assert check_hyps(C, c["closed_roles_ijklmp"], closed=True), name
        words = sorted(C, key=lambda s: (len(s), sorted(s)))
        lit = wrap([fs(w) for w in words], "   ")
        data_b.append(f"""
/-- {name}: {len(C)} codewords, {len(maximal(C))} maximal. -/
def {name} : Finset (Finset (Fin 7)) :=
  {{{lit.lstrip()}}}

/-- {name}: roles `(i,j,k,l,m,p)` for Theorem 1(b). -/
def {name}.openRoles : Roles 7 := {roles(c["open_roles_ijklmp"])}

/-- {name}: roles `(i,j,k,l,m,p)` for Theorem 1(a). -/
def {name}.closedRoles : Roles 7 := {roles(c["closed_roles_ijklmp"])}
""")
        conv_b.append(f"""
theorem {name}.hyps :
    Hyps1b {name} {name}.openRoles ∧ Hyps1a {name} {name}.closedRoles := by
  decide +kernel

theorem {name}.not_convex : ¬ IsOpenConvex {name} ∧ ¬ IsClosedConvex {name} :=
  not_convex_of_hyps {name}.hyps

theorem {name}.isNeuralCode : IsNeuralCode {name} := by
  decide +kernel
""")
        entries = []
        for s in missing_faces(C):
            r = collapse_to_vertex(link_delta(C, s))
            assert r is not None, (name, sorted(s))
            steps, v = r
            st = wrap([f"({fs(a)}, {fs(b)})" for a, b in steps], "      ")
            entries.append(f"    ({fs(s)}, [\n{st}], {v})")
        total_faces += len(entries)
        body = "[\n" + ",\n".join(entries) + "]" if entries else "[]"
        links_b.append(f"""
/-- {name}: {len(entries)} faces to check. -/
def {name}.cert : List (LinkCert 7) := {body}

theorem {name}.certOK : CertOK {name} {name}.cert := by
  decide +kernel

theorem {name}.locallyGoodC : LocallyGoodC {name} :=
  locallyGoodC_of_certOK {name}.certOK

theorem {name}.linksCollapsible : LinksCollapsible {name} :=
  {name}.locallyGoodC.linksCollapsible
""")

    write(out / "Data.lean", "import RimRule.Defs\n", DATA_DOC, "".join(data_b))
    write(out / "Basic.lean", "import RimRule.Main\nimport RimRule.Theorem1a\n", "", BASIC,
          namespace=False)
    size = -(-len(codes) // CHUNKS)
    mods = []
    for k in range(CHUNKS):
        sl = slice(k * size, (k + 1) * size)
        write(out / f"Convex{k + 1}.lean", "import RimRule.Rim70.Data\nimport RimRule.Rim70.Basic\n",
              CONVEX_DOC.format(part=k + 1, total=CHUNKS), "".join(conv_b[sl]))
        # Links{k} imports Convex{k} only to order the build, so at most CHUNKS heavy Lean
        # processes run at once (four at once ran out of memory on an 8 GB machine).
        write(out / f"Links{k + 1}.lean",
              f"import RimRule.Rim70.Convex{k + 1}\nimport RimRule.LocallyGood\n",
              LINKS_DOC.format(part=k + 1, total=CHUNKS), "".join(links_b[sl]))
        mods += [f"RimRule.Rim70.Convex{k + 1}", f"RimRule.Rim70.Links{k + 1}"]

    names = [c["id"] for c in codes]
    cases = "".join(f"  · exact ⟨{nm}.isNeuralCode, {nm}.locallyGoodC, {nm}.not_convex.1,\n"
                    f"      {nm}.not_convex.2⟩\n"
                    for nm in names)
    pats = "\n      | ".join(" | ".join(["rfl"] * min(12, len(names) - i)) for i in range(0, len(names), 12))
    summ = f"""
/-- The {len(names)} codes of `data/rim70.json`. -/
def all70 : List (Finset (Finset (Fin 7))) :=
  [{wrap(names, "   ").lstrip()}]

theorem length_all70 : all70.length = {len(names)} := rfl

/-- The {len(names)} codes are pairwise distinct (as codes on the labelled neurons; that they are
also pairwise non-isomorphic under relabelling is checked in Python, not in Lean). -/
theorem all70_nodup : all70.Nodup := by
  decide +kernel

/-- Every code in `all70` is a neural code (`∅ ∈ C`), satisfies `LocallyGoodC` (every nonempty
non-codeword face of `Δ(C)` has a collapsible link), and is neither open-convex nor
closed-convex. -/
theorem all70_spec :
    ∀ C ∈ all70, IsNeuralCode C ∧ LocallyGoodC C ∧ ¬ IsOpenConvex C ∧ ¬ IsClosedConvex C := by
  intro C hC
  simp only [all70, List.mem_cons, List.not_mem_nil, or_false] at hC
  rcases hC with {pats}
{cases}"""
    summ_doc = f"""/-!
# Stage 8 summary

`all70` lists the {len(names)} codes of `data/rim70.json`; `all70_nodup` says they are distinct.
`all70_spec`: each is a neural code, satisfies `LocallyGoodC`, and is neither open-convex nor
closed-convex (Theorem 1). With the one cited fact collapsible ⇒ contractible (not proved
here; see `RimRule/LocallyGood.lean`), `LocallyGoodC` means locally good, so each code is a
counterexample to Conjecture 3.13 of Gambacini–Jeffs–Macdonald–Shiu (`RimRule/Conj313.lean`).
-/
"""
    write(out / "Summary.lean", "".join(f"import {m}\n" for m in mods), summ_doc, summ)
    print(f"{len(codes)} codes, {total_faces} faces")


if __name__ == "__main__":
    main()
